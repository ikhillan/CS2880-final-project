"""Authenticate public replay aggregates and rebuild manuscript tables.

No applicant, listing or cached-response records are required. This formats
already completed inference; the root release rebuilds intervals from seed
counts. All numerical selections are explicit and missing rows are errors.
"""
import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
WINDOWS = [('stage1_pilot', 'Development 2026'),
           ('heldout_primary', 'Held-out 2026'),
           ('heldout_replication', 'Replication 2025')]
VARIANTS = [('primary', 'Ordinary'), ('enriched', 'Enriched')]
POLICIES = [('random', 'Random'), ('gpt', 'GPT'), ('score', 'Score'),
            ('anchor_random', r'$A(\mathrm{Random})$'),
            ('anchor_gpt', r'$A(\mathrm{GPT})$'),
            ('anchor_score', r'$A(\mathrm{Score})$'),
            ('balanced_gpt', r'$B(\mathrm{GPT})$'),
            ('balanced_score', r'$B(\mathrm{Score})$'),
            ('score_anchor_gpt', r'$A_s(\mathrm{GPT})$')]


def one(rows, require_estimate=True, **criteria):
    found = [r for r in rows if all(r[k] == v for k, v in criteria.items())]
    if len(found) != 1:
        raise ValueError(f'Expected one row for {criteria}, found {len(found)}')
    if require_estimate and found[0].get('status', 'ok') != 'ok':
        raise ValueError(f'Undefined selected estimate: {criteria}')
    return found[0]


def pp(row, intervals=False, simultaneous=False):
    point = 100 * float(row['mean'])
    if not intervals:
        return f'${point:+.2f}$'
    prefix = 'simultaneous_' if simultaneous else ''
    lo, hi = (100 * float(row[prefix + k]) for k in ('lo', 'hi'))
    if not lo <= point <= hi:
        raise ValueError('Selected interval excludes point estimate')
    return f'${point:+.2f}$ [{lo:.2f}, {hi:.2f}]'


def table(name, spec, header, rows):
    text = '% Generated by rental-access/rebuild.py; do not edit.\n'
    text += r'\begin{tabular}{@{}' + spec + r'@{}}\toprule' + '\n'
    text += header + r'\\\midrule' + '\n'
    text += '\n'.join(' & '.join(row) + r' \\' for row in rows)
    text += '\n' + r'\bottomrule\end{tabular}' + '\n'
    (HERE / name).write_text(text)


def main():
    provenance = json.loads((HERE / 'provenance.json').read_text())
    for info in provenance.get('public_reproduction', {}).values():
        path = HERE.parents[2] / info['repository_path']
        if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() != info['sha256']:
            raise ValueError(f'Public reproduction hash mismatch: {path}')
    data = {}
    for path, info in provenance['sources'].items():
        raw = (HERE / path).read_bytes()
        if hashlib.sha256(raw).hexdigest() != info['sha256']:
            raise ValueError(f'Hash mismatch: {path}')
        if path.endswith('.csv'):
            data[Path(path).stem] = list(csv.DictReader(raw.decode().splitlines()))
    run = json.loads((HERE / 'sources/manifest.json').read_text())
    raw_inputs = (HERE / 'input-provenance.json').read_bytes()
    assert hashlib.sha256(raw_inputs).hexdigest() == provenance['input_provenance_sha256']
    inputs = json.loads(raw_inputs)
    assert inputs['packet_sha256'] == run['packet_sha256']
    assert inputs['counts'] == {'planned': 1600, 'exported': 1280, 'skipped': 320}
    assert inputs['skip_boroughs'] == {'Staten Island': 320}
    assert inputs['api_calls'] == 0
    assert sum(r['candidate_hashes_verified'] for r in inputs['cache_validation'].values()) == 55115
    assert len(inputs['archived_reproduction_checks']) == 54
    assert all(r['matches'] for r in inputs['archived_reproduction_checks'])
    assert run['markets'] == 1280 and run['complete_shards'] == 20
    assert run['post_hoc_followup'] and run['bootstrap_draws'] == 10000
    assert len(data['reproduction']) == 36
    assert all(abs(float(r['difference_pp'])) < 1e-9 for r in data['reproduction'])
    assert len(data['primary']) == 48
    for r in data['primary']:
        assert r['status'] == 'ok' and int(r['seeds_available']) == 20
        assert int(r['valid_bootstrap_draws']) == 10000
        assert r['simultaneous_family_complete'] == 'True'
        assert float(r['family_size']) == 8

    def primary(w, v, metric, arm='anchor_gpt', comparator='gpt'):
        return one(data['primary'], window=w, variant=v, group='all',
                   metric=metric, arm=arm, comparator=comparator)

    def level(w, v, arm, metric):
        return one(data['levels'], window=w, variant=v, group='all',
                   arm=arm, metric=metric)

    def transition(w, v, metric, group='all', arm='anchor_gpt', baseline='gpt'):
        return one(data['transitions'], require_estimate=False, window=w, variant=v, group=group,
                   arm=arm, baseline=baseline, metric=metric)

    rows, balancing, ties = [], [], []
    for variant, design in VARIANTS:
        for w, label in WINDOWS:
            pl, cv = (primary(w, variant, m) for m in ('placed', 'coverage_market_mean'))
            ex = transition(w, variant, 'gross_exits')
            en = transition(w, variant, 'gross_entrants')
            total = round(float(ex['denominator_total']))
            net = float(en['numerator_total']) - float(ex['numerator_total'])
            assert abs(net / total - float(pl['mean'])) < 1e-10
            rows.append([design, label, pp(pl, True, True), pp(cv, True, True),
                         f"{round(float(ex['numerator_total'])):,}/{total:,}"])
            bex = transition(w, variant, 'gross_exits', arm='balanced_gpt', baseline='anchor_gpt')
            balancing.append([design, label] + [
                pp(primary(w, variant, m, 'balanced_gpt', 'anchor_gpt'), True, True)
                for m in ('placed', 'coverage_market_mean')] + [f"{round(float(bex['numerator_total'])):,}"])
            tie = transition(w, variant, 'gross_exits', arm='anchor_gpt_ties')
            ties.append([design, label,
                         f"{100*float(level(w, variant, 'anchor_gpt_ties', 'placed')['mean']):.2f}",
                         f"{100*float(level(w, variant, 'anchor_gpt_ties', 'coverage_market_mean')['mean']):.2f}",
                         f"{float(tie['numerator_total']):.2f}"])
    table('main-table.tex', 'llrrr',
          r'Design & Window & $\Delta$ placement & $\Delta$ coverage & Exits / appearances', rows)
    table('balanced-table.tex', 'llrrr',
          r'Design & Window & $\Delta$ placement & $\Delta$ coverage & Exits', balancing)
    table('ties-table.tex', 'llrrr',
          r'Design & Window & Placed (\%) & Coverage (\%) & Expected exits', ties)

    for variant, _ in VARIANTS:
        rows = []
        for arm, label in POLICIES:
            row = [label]
            for w, _ in WINDOWS:
                for metric in ('placed', 'coverage_market_mean'):
                    row.append(f"{100*float(level(w, variant, arm, metric)['mean']):.2f}")
            rows.append(row)
        table(f'controls-{variant}.tex', 'lrrrrrr',
              r'& \multicolumn{2}{c}{Development 2026} & \multicolumn{2}{c}{Held-out 2026} & \multicolumn{2}{c}{Replication 2025}\\'
              '\n' + r'Policy & Placed & Coverage & Placed & Coverage & Placed & Coverage', rows)

    rows = []
    groups = [('all', 'All'), ('lower_income', 'Lower income'),
              ('higher_income', 'Higher income'), ('degree_0', '0 options'),
              ('degree_1_5', '1--5 options'), ('degree_6_10', '6--10 options'),
              ('degree_11_plus', '11+ options')]
    for variant, design in VARIANTS:
        for group, label in groups:
            values = []
            for metric in ('group_count', 'gross_exits', 'gross_entrants', 'rank_worse'):
                total = sum(float(transition(w, variant, metric, group)['numerator_total'])
                            for w, _ in WINDOWS)
                if abs(total - round(total)) > 1e-6:
                    raise ValueError('Noninteger transition count')
                values.append(f'{round(total):,}')
            rows.append([design, label] + values)
    table('groups-table.tex', 'llrrrr',
          r'Design & Group & Appearances & Exits & Entrants & Worse rank', rows)

    rows = []
    for variant, design in VARIANTS:
        for w, label in WINDOWS:
            row = [design, label]
            for metric in ('placed', 'coverage_market_mean'):
                r = one(data['contrasts'], window=w, variant=variant, group='all',
                        arm='score_anchor_gpt', comparator='anchor_gpt', metric=metric)
                row.append(pp(r, True))
            rows.append(row)
    table('score-table.tex', 'llrr',
          r'Design & Window & $\Delta$ placement & $\Delta$ coverage', rows)
    print('Verified six source files, all 36 placement checks, 48 primary intervals; rebuilt seven tables.')


if __name__ == '__main__':
    main()
