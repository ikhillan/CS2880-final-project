"""Verify released jobs aggregates and rebuild the manuscript's point table.

This is an aggregate calculation, not a new market replay. In particular,
the released tables do not identify the paired uncertainty of anchored GPT
minus anchored random, or the anchor's coverage and individual transitions.
"""
import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def one(rows, **criteria):
    found = [row for row in rows if all(row[k] == v for k, v in criteria.items())]
    if len(found) != 1:
        raise ValueError(f"Expected one row for {criteria}, found {len(found)}")
    return found[0]


def main():
    manifest = json.loads((HERE / "provenance.json").read_text())
    sources = {}
    for path, entry in manifest["sources"].items():
        raw = (HERE / path).read_bytes()
        if hashlib.sha256(raw).hexdigest() != entry["sha256"]:
            raise ValueError(f"Source hash mismatch: {path}")
        sources[path] = list(csv.DictReader(raw.decode().splitlines()))
    results, bounds, tex = [], [], []
    for window in ("frozen", "replication"):
        pair = one(sources[f"sources/{window}-accuracy_pairs.csv"],
                   rule="GPT (5 jobs)", baseline="Random (5 jobs)", group="all")
        anchors = sources[f"sources/{window}-anchor.csv"]
        gpt = one(anchors, variant="primary", rule="GPT (5 jobs)")
        random = one(anchors, variant="primary", rule="Random (5 jobs)")
        placed = 100 * float(pair["d_placed"])
        if abs(placed - float(gpt["placed"]) + float(random["placed"])) > 1e-9:
            raise ValueError(f"Placement sources disagree: {window}")
        gain = float(gpt["anchor_placed"]) - float(gpt["placed"])
        if abs(gain - float(gpt["gain"])) > 1e-9:
            raise ValueError(f"Anchor gain sources disagree: {window}")
        coverage = 100 * float(pair["d_accurate"])
        coordinated_gap = float(gpt["anchor_placed"]) - float(random["anchor_placed"])
        result = {"window": window, "gpt_minus_random_coverage_pp": coverage,
                  "gpt_minus_random_placement_pp": placed,
                  "anchor_gain_pp": gain, "anchored_gpt_minus_anchored_random_pp": coordinated_gap,
                  "coordinated_gap_interval": "not identified by released aggregate tables"}
        for metric in ("accurate", "placed"):
            low = 100 * float(pair[f"d_{metric}_lo"])
            high = 100 * float(pair[f"d_{metric}_hi"])
            point = coverage if metric == "accurate" else placed
            if not low <= point <= high:
                raise ValueError(f"Interval excludes estimate: {window} {metric}")
            result[f"gpt_minus_random_{metric}_lo_pp"] = low
            result[f"gpt_minus_random_{metric}_hi_pp"] = high
        results.append(result)
        # Each primary market contains 24 seekers and is equally weighted.
        # The frozen/replication designs have 240/160 markets, respectively.
        population = 24 * {"frozen": 240, "replication": 160}[window]
        counts = {}
        for key in ("placed", "anchor_placed", "lists_changed"):
            value = population * float(gpt[key]) / 100
            count = round(value)
            if abs(value - count) > 1e-6 or not 0 <= count <= population:
                raise ValueError(f"Cannot reconstruct count: {window} {key}")
            counts[key] = count
        before, after = counts["placed"], counts["anchor_placed"]
        changed = counts["lists_changed"]
        delta = after - before
        lower = max(0, -delta)
        upper = min(before, population - after, changed - max(delta, 0))
        if not 0 <= lower <= upper:
            raise ValueError(f"Inconsistent transition bounds: {window}")
        bounds.append({"window": window, "observations": population,
                       "placed_before": before, "placed_after": after,
                       "changed_menus": changed, "net_entries": delta,
                       "gross_exit_lower": lower, "gross_exit_upper": upper,
                       "gross_exit_upper_pct_all": 100 * upper / population,
                       "interpretation": "valid outer interval; not observed exits or sharp identified bounds"})
        values = (f"{coverage:+.1f}", f"{placed:+.1f}", f"{gain:+.1f}", f"{coordinated_gap:+.2f}")
        tex.append(window.title() + " & " + " & ".join(f"${x}$" for x in values) + r" \\")
    header = (
        "% Generated by jobs/rebuild.py from verified released aggregates.\n"
        r"\begin{tabular}{@{}lrrrr@{}}\toprule" "\n"
        r"& \multicolumn{2}{c}{GPT minus random} & \multicolumn{2}{c}{Anchored GPT placement minus}\\" "\n"
        r"Window & Coverage & Placement & Original GPT & Anchored random\\\midrule" "\n"
    )
    (HERE / "table.tex").write_text(header + "\n".join(tex) + "\n" + r"\bottomrule\end{tabular}" + "\n")
    with (HERE / "summary.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(results[0]))
        writer.writeheader()
        writer.writerows(results)
    with (HERE / "access-bounds.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(bounds[0]))
        writer.writeheader()
        writer.writerows(bounds)
    print("Verified four source tables; rebuilt jobs/table.tex, jobs/summary.csv and jobs/access-bounds.csv.")


if __name__ == "__main__":
    main()
